-- Initial schema. Portable across H2 2.x (dev) and PostgreSQL (prod).

CREATE TABLE city (
    city_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city_name VARCHAR(255)
);

CREATE TABLE airport (
    airport_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    airport_name      VARCHAR(255),
    airport_iata_code VARCHAR(3),
    city_id           BIGINT REFERENCES city (city_id)
);

CREATE TABLE airline (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    iso  VARCHAR(255) NOT NULL
);

CREATE TABLE airplane (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    manufacturer    VARCHAR(255),
    model           VARCHAR(255),
    number_of_seats BIGINT,
    speed           DOUBLE PRECISION NOT NULL,
    airline_id      BIGINT
);

CREATE TABLE flight (
    flight_id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    departure_date       DATE,
    departure_time       TIME,
    arrival_time         TIME,
    price                BIGINT,
    airline_id           BIGINT REFERENCES airline (id),
    departure_airport_id BIGINT REFERENCES airport (airport_id),
    arrival_airport_id   BIGINT REFERENCES airport (airport_id)
);

CREATE TABLE roles (
    id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(20) NOT NULL UNIQUE
);

CREATE TABLE users (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name     VARCHAR(255),
    username VARCHAR(255) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    email    VARCHAR(255) NOT NULL UNIQUE
);

CREATE TABLE user_roles (
    user_id BIGINT  NOT NULL REFERENCES users (id),
    role_id INTEGER NOT NULL REFERENCES roles (id),
    PRIMARY KEY (user_id, role_id)
);

CREATE TABLE cart (
    cart_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id   BIGINT REFERENCES users (id),
    flight_id BIGINT REFERENCES flight (flight_id)
);
